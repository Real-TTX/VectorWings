using MatGame.Sdk;
using Npgsql;
using VectorWings.Core;

namespace VectorWings.Module;

public sealed record Progress(int Matches, int Missions, int BestScore);
public sealed record ResultRow(long Id, string Mode, int Mission, bool? Success, DateTime Date, int Participants);
public sealed record ProgressRow(long AccountId, string Name, Progress Progress);

public sealed class ProgressStore(NpgsqlDataSource database)
{
    private readonly SemaphoreSlim writes = new(1);
    private readonly HashSet<long> deleted = [];

    public async Task InitializeAsync(CancellationToken ct)
    {
        await using var command = database.CreateCommand("""
            CREATE SCHEMA IF NOT EXISTS vectorwings;
            CREATE TABLE IF NOT EXISTS vectorwings."Match" (
              "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              "Token" uuid NOT NULL UNIQUE,
              "Mode" text NOT NULL,
              "Mission" integer NOT NULL,
              "Success" boolean NULL,
              "CreateDate" timestamptz NOT NULL DEFAULT now(),
              "UpdateDate" timestamptz NOT NULL DEFAULT now(),
              "CreateUserId" bigint NOT NULL DEFAULT 0,
              "UpdateUserId" bigint NOT NULL DEFAULT 0
            );
            CREATE TABLE IF NOT EXISTS vectorwings."PilotResult" (
              "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              "MatchId" bigint NOT NULL REFERENCES vectorwings."Match"("Id") ON DELETE CASCADE,
              "AccountId" bigint NOT NULL,
              "Score" integer NOT NULL,
              "CreateDate" timestamptz NOT NULL DEFAULT now(),
              "UpdateDate" timestamptz NOT NULL DEFAULT now(),
              "CreateUserId" bigint NOT NULL DEFAULT 0,
              "UpdateUserId" bigint NOT NULL DEFAULT 0,
              UNIQUE ("MatchId", "AccountId")
            );
            CREATE INDEX IF NOT EXISTS "PilotResult_AccountId" ON vectorwings."PilotResult" ("AccountId");
            """);
        await command.ExecuteNonQueryAsync(ct);
    }

    public async Task SaveAsync(MatchResult result, CancellationToken ct)
    {
        await writes.WaitAsync(ct);
        try
        {
            await using var connection = await database.OpenConnectionAsync(ct);
            await using var transaction = await connection.BeginTransactionAsync(ct);
            await using var match = new NpgsqlCommand("""
                INSERT INTO vectorwings."Match" ("Token", "Mode", "Mission", "Success")
                VALUES ($1, $2, $3, $4)
                ON CONFLICT ("Token") DO UPDATE SET "Token" = EXCLUDED."Token"
                RETURNING "Id"
                """, connection, transaction);
            match.Parameters.AddWithValue(result.Token);
            match.Parameters.AddWithValue(result.Mode.ToString());
            match.Parameters.AddWithValue(result.Mission);
            match.Parameters.AddWithValue(NpgsqlTypes.NpgsqlDbType.Boolean, (object?)result.Success ?? DBNull.Value);
            var id = (long)(await match.ExecuteScalarAsync(ct))!;
            foreach (var pilot in result.Players.Where(p => !deleted.Contains(p.AccountId)))
            {
                await using var standing = new NpgsqlCommand("""
                    INSERT INTO vectorwings."PilotResult" ("MatchId", "AccountId", "Score", "CreateUserId", "UpdateUserId")
                    VALUES ($1, $2, $3, $2, $2) ON CONFLICT ("MatchId", "AccountId") DO NOTHING
                    """, connection, transaction);
                standing.Parameters.AddWithValue(id);
                standing.Parameters.AddWithValue(pilot.AccountId);
                standing.Parameters.AddWithValue(pilot.Score);
                await standing.ExecuteNonQueryAsync(ct);
            }
            await transaction.CommitAsync(ct);
        }
        finally { writes.Release(); }
    }

    public async Task RemoveAccountAsync(long accountId, CancellationToken ct)
    {
        await writes.WaitAsync(ct);
        try
        {
            deleted.Add(accountId);
            await using var command = database.CreateCommand("""DELETE FROM vectorwings."PilotResult" WHERE "AccountId" = $1""");
            command.Parameters.AddWithValue(accountId);
            await command.ExecuteNonQueryAsync(ct);
        }
        finally { writes.Release(); }
    }

    public async Task<Progress> ProfileAsync(long accountId, CancellationToken ct)
    {
        await using var command = database.CreateCommand("""
            SELECT count(*)::int,
                   count(DISTINCT m."Mission") FILTER (WHERE m."Mode" = 'Campaign' AND m."Success" = true)::int,
                   coalesce(max(p."Score"), 0)
            FROM vectorwings."PilotResult" p JOIN vectorwings."Match" m ON m."Id" = p."MatchId"
            WHERE p."AccountId" = $1
            """);
        command.Parameters.AddWithValue(accountId);
        await using var reader = await command.ExecuteReaderAsync(ct);
        await reader.ReadAsync(ct);
        return ReadProgress(reader, 0);
    }

    internal async Task<ResultRow[]> ResultsAsync(CancellationToken ct)
    {
        await using var command = database.CreateCommand("""
            SELECT m."Id", m."Mode", m."Mission", m."Success", m."CreateDate", count(p."Id")::int
            FROM vectorwings."Match" m LEFT JOIN vectorwings."PilotResult" p ON m."Id" = p."MatchId"
            GROUP BY m."Id" ORDER BY m."Id" DESC LIMIT 100
            """);
        await using var reader = await command.ExecuteReaderAsync(ct);
        var results = new List<ResultRow>();
        while (await reader.ReadAsync(ct))
            results.Add(new(reader.GetInt64(0), reader.GetString(1), reader.GetInt32(2),
                reader.IsDBNull(3) ? null : reader.GetBoolean(3), reader.GetDateTime(4), reader.GetInt32(5)));
        return results.ToArray();
    }

    internal async Task<ProgressRow[]> PlayersAsync(IGameAccounts accounts, CancellationToken ct)
    {
        await using var command = database.CreateCommand("""
            SELECT p."AccountId", count(*)::int,
                   count(DISTINCT m."Mission") FILTER (WHERE m."Mode" = 'Campaign' AND m."Success" = true)::int,
                   coalesce(max(p."Score"), 0)
            FROM vectorwings."PilotResult" p JOIN vectorwings."Match" m ON m."Id" = p."MatchId"
            GROUP BY p."AccountId"
            """);
        await using var reader = await command.ExecuteReaderAsync(ct);
        var progress = new Dictionary<long, Progress>();
        while (await reader.ReadAsync(ct)) progress.Add(reader.GetInt64(0), ReadProgress(reader, 1));
        var names = await accounts.FindManyAsync(progress.Keys, ct);
        return names.Select(pair => new ProgressRow(pair.Key, pair.Value.Name, progress[pair.Key])).ToArray();
    }

    private static Progress ReadProgress(NpgsqlDataReader reader, int firstColumn) =>
        new(reader.GetInt32(firstColumn), reader.GetInt32(firstColumn + 1), reader.GetInt32(firstColumn + 2));
}
